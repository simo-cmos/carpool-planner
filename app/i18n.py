def normalize_language(language: str | None) -> str:
    """Return a supported language code."""
    if not language:
        return "en"
    cleaned = str(language).strip().lower()
    return cleaned if cleaned in SUPPORTED_LANGUAGES else "en"


def translate(language: str | None, key: str, **kwargs: Any) -> str:
    """Translate one UI string with English fallback."""
    normalized = normalize_language(language)
    template = TRANSLATIONS.get(normalized, {}).get(key, key)
    try:
        return template.format(**kwargs)
    except Exception:
        return template
